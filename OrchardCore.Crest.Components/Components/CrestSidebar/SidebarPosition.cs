namespace Crest.Components.Primitives;

/// <summary>
/// Specifies the ways a <see cref="Crest.Components.Primitives.CrestSidebar" /> component renders inside CrestLayout.
/// </summary>
public enum SidebarPosition
{
    /// <summary>
    /// The CrestSidebar component is displayed at the start of CrestLayout.
    /// </summary>
    Left,

    /// <summary>
    /// The CrestSidebar component is displayed at the end of CrestLayout.
    /// </summary>
    Right,

    /// <summary>
    /// The CrestSidebar component is displayed at the start of CrestLayout.
    /// </summary>
    Start,

    /// <summary>
    /// The CrestSidebar component is displayed at the end of CrestLayout.
    /// </summary>
    End
}

