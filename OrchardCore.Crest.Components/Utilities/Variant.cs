namespace Crest.Components.Primitives;

/// <summary>
/// Specifies the design variant of <see cref="Crest.Components.Primitives.CrestButton" /> and <see cref="Crest.Components.Primitives.CrestBadge" />. Affects the visual styling of CrestButton and CrestBadge.
/// </summary>
public enum Variant
{
    /// <summary>
    /// A filled appearance.
    /// </summary>
    Filled,

    /// <summary>
    /// A flat appearance without any drop shadows.
    /// </summary>
    Flat,

    /// <summary>
    /// A text appearance.
    /// </summary>
    Text,

    /// <summary>
    /// An outlined appearance.
    /// </summary>
    Outlined
}

